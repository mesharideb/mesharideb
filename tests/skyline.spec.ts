import { test, expect, type Page } from "@playwright/test"
import snapshot from "../data/contributions.json" with { type: "json" }

const settled = (page: Page) => expect(page.locator("canvas")).toHaveAttribute("data-settled", "true")
const picture = (page: Page) => page.locator("canvas").evaluate((el: HTMLCanvasElement) => el.toDataURL())
test("renders real data, switches views, and supports keyboard dates and the table", async ({ page }) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message))
  await page.goto("/")
  await expect(page.locator("canvas")).toHaveAttribute("data-progress", "1.000")
  await settled(page)
  await expect(page.getByRole("heading", { level: 2 })).toContainText(snapshot.totalContributions.toLocaleString("en-US"))
  await page.getByRole("button", { name: "Flat heat map", exact: true }).click()
  await expect(page.locator("canvas")).toHaveAttribute("data-progress", "0.000")
  await page.locator("canvas").focus(); await page.keyboard.press("Home")
  await expect(page.getByRole("tooltip")).toContainText(new Date(snapshot.from + "T00:00:00Z").toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric", timeZone: "UTC" }))
  await page.keyboard.press("End")
  await expect(page.locator("[aria-live=polite]")).toContainText("contributions on")
  await page.keyboard.press("Escape"); await expect(page.getByRole("tooltip", { includeHidden: true })).toHaveAttribute("aria-hidden", "true")
  await page.getByText("View daily contributions as a table").click()
  await expect(page.locator("tbody tr")).toHaveCount(365)
  await page.getByRole("button", { name: "3D skyline", exact: true }).click()
  await expect(page.locator("canvas")).toHaveAttribute("data-progress", "1.000")
  expect(errors).toEqual([])
})
test("orbit, reset, palettes and legend change the actual canvas", async ({ page }) => {
  await page.goto("/?theme=light"); await settled(page)
  await expect(page.locator("canvas")).toHaveAttribute("data-progress", "1.000")
  const original = await picture(page), bounds = await page.locator("canvas").boundingBox()
  const x = bounds!.x + bounds!.width / 2, y = bounds!.y + bounds!.height / 2
  await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + 65, y - 20, { steps: 8 }); await page.mouse.up(); await page.mouse.move(1, 1)
  await settled(page); expect(await picture(page)).not.toBe(original)
  await page.getByRole("button", { name: "Reset view" }).click(); await settled(page)
  expect(await picture(page)).toBe(original)
  await page.getByLabel("Color palette").selectOption("ocean"); await settled(page)
  expect(await picture(page)).not.toBe(original)
  const blue = await picture(page)
  await page.getByRole("button", { name: "Highlight heaviest days" }).hover(); await settled(page)
  expect(await picture(page)).not.toBe(blue)
  await page.getByRole("button", { name: "Switch to dark theme" }).click(); await settled(page)
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark")
})
test("mobile stays within the viewport and accepts touch selection", async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 850 })
  await page.goto("/"); await settled(page)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
  await page.getByRole("button", { name: "Flat heat map", exact: true }).click(); await settled(page)
  await expect(page.locator(".stat-row")).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
})
test("normal motion passes through intermediate frames and ends in both views", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "no-preference" })
  await page.goto("/")
  await expect(page.locator("canvas")).toHaveAttribute("data-progress", "1.000")
  await page.getByRole("button", { name: "Flat heat map", exact: true }).click()
  await expect.poll(async () => Number(await page.locator("canvas").getAttribute("data-progress"))).toBeLessThan(1)
  await expect(page.locator("canvas")).toHaveAttribute("data-progress", "0.000")
  await settled(page)
})
test("profile output renders both themes without interactive controls or external requests", async ({ page }) => {
  const external: string[] = []
  page.on("request", request => { if (!new URL(request.url()).hostname.match(/^(127\.0\.0\.1|localhost)$/)) external.push(request.url()) })
  for (const theme of ["light", "dark"]) {
    await page.goto(`/?profile=1&theme=${theme}`); await settled(page)
    await expect(page.getByTestId("profile-render")).toBeVisible()
    await expect(page.locator("canvas")).toHaveAttribute("data-progress", "1.000")
    await expect(page.getByRole("group", { name: "Chart view" })).toHaveCount(0)
    await expect(page.locator("html")).toHaveAttribute("data-theme", theme)
  }
  expect(external).toEqual([])
})
